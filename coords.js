  function toGeo(list) {
    const out = {};
    Object.keys(list).forEach(name => {
      out[name] = {
        lat: list[name][0],
        lng: list[name][1],
        source: SRC,
        coordinateSystem: 'WGS84',
        note: NOTE
      };
    });
    return out;
  }

