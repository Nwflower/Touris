/* ==========================================================================
   Touris 知途 · 城市数据协议

   三个城市走同一套协议，没有「京都走遗留分支、北京上海走新路径」这种事——
   那是原型里的主要技术债（data.js 导出 PLANS_DEFAULT，city-data.js 导出
   plansDefault，靠 app.js 的三元表达式切换）。

   ★ 每个城市要提供什么

     key/maxDays              标识与行程天数上限
     spots                    景点，来自 CITY_SEED，带 prefer/avoid 语义
     poi                      归一化坐标，画示意路线用
     images                   图片 URL
     dine                     餐饮候选（按区域成组，只说「某某一带」不给店名地址）
     stay                     住宿候选，按风格分组
     routeDefault[N]          第 N 天的默认走法（未使用记忆时的方案）
     cultureRoutes            偏文化取向的走法（记忆版本里的备选）

   ★ 这里没有 plansDefault / plansMemory 两份手写数据

   「用记忆」和「不用记忆」的差别，由 memory/derive.js 从记忆的语义标签**推导**出来，
   不在这里手写第二份。加城市的成本因此只有「填景点和路线」，对照自动成立。
   ========================================================================== */

const CITY_DATA = {};

/* ---------------- 工厂函数 ----------------
   字段名写错会被 validate.js 抓住，这里收敛默认值，让城市定义保持短。 */

function spot(name, extra){
  const base = (typeof CITY_SEED !== 'undefined' && CITY_SEED.spots[name]) || {};
  return Object.assign({ name, cat:'temple', score:4.5, count:0, src:'大众点评',
    intro:'', prefer:[], avoid:[] }, base, extra || {});
}

function dine(area, theme, walk, picks){ return { area, theme, walk, picks: picks || [] }; }

/** 一条餐饮候选。原型定下的商业口径：只给「某某一带」+ 候选类型，不给具体店名地址。 */
function pick(style, cuisine, price, score, count, note){
  return { style, cuisine, price, score, count, src:'大众点评', note:note || '' };
}

function stay(area, theme, note, picks){ return { area, theme, note, picks: picks || [] }; }

function room(style, type, price, score, count, note){
  return { style, type, price, score, count, src:'大众点评', note:note || '' };
}

/** 一条一日路线。
    spots 是景点名数组（会按记忆约束过滤）。
    theme   当天主题，如「锦市场开场 · 傍晚东山」
    paceNote 节奏说明，如「09:30 出发 · 步行 8.6km」
    times   可选，与 spots 一一对应的出发时间，用来排时间轴
    durs    可选，与 spots 一一对应的停留时长
    notes   可选，与 spots 一一对应的备注 */
function day(n, spots, o){
  o = o || {};
  return {
    n,
    spots: spots || [],
    theme: o.theme || '',
    paceNote: o.paceNote || '',
    times: o.times || [],
    durs: o.durs || [],
    notes: o.notes || []
  };
}

